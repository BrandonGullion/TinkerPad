//! Generates the reference pages under `docs/reference/` (work item 05-04).
//!
//! Every page here is produced from the Rust types that actually do the work:
//! the manifest schema from the types the loader deserialises, the helper
//! protocol from the messages the pool sends and receives, the dump schema
//! from the values the output pane renders. Nothing is transcribed, because a
//! document that duplicates a type drifts within a month and then lies.
//!
//!     tinkerpad-docgen            write the pages
//!     tinkerpad-docgen --check    fail if what is committed is out of date
//!
//! CI runs the second one. A type changed without regenerating is a failed
//! build, not a stale page nobody noticed.

use std::path::{Path, PathBuf};

use tinkerpad_core::dump::Column;
use tinkerpad_core::{RichNode, RichValue};
use tinkerpad_plugin::helper::{FromHelper, HookRequest, ToHelper};

fn main() {
    let check = std::env::args().any(|arg| arg == "--check");
    let dir = reference_dir();
    if let Err(error) = std::fs::create_dir_all(&dir) {
        eprintln!("could not make {}: {error}", dir.display());
        std::process::exit(2);
    }

    let pages = [
        ("plugin-toml.schema.json", manifest_schema()),
        ("manifest.md", manifest_page()),
        ("helper-protocol.md", helper_page()),
        ("dump.md", dump_page()),
    ];

    let mut stale = Vec::new();
    for (name, text) in pages {
        let path = dir.join(name);
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        // Written by this tool on every platform, so compare without the
        // line endings a checkout may have changed.
        if current.replace("\r\n", "\n") == text {
            continue;
        }
        if check {
            stale.push(name);
            continue;
        }
        match std::fs::write(&path, &text) {
            Ok(()) => println!("wrote {}", path.display()),
            Err(error) => {
                eprintln!("could not write {}: {error}", path.display());
                std::process::exit(2);
            }
        }
    }

    if !stale.is_empty() {
        eprintln!(
            "out of date: {}\n\nA type these are generated from has changed. Run:\n\
             \n    cargo run -p tinkerpad-plugin --bin tinkerpad-docgen\n\n\
             and commit what it writes.",
            stale.join(", ")
        );
        std::process::exit(1);
    }
    if check {
        println!("docs/reference is up to date");
    }
}

fn reference_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/reference")
}

/// A note at the top of every generated page, so nobody edits one by hand.
fn generated_by(what: &str) -> String {
    format!(
        "<!-- Generated by `cargo run -p tinkerpad-plugin --bin tinkerpad-docgen`.\n\
         \x20    Edit {what} instead; this file is overwritten. -->\n\n"
    )
}

// --- the manifest ---------------------------------------------------------

fn manifest_schema() -> String {
    let mut value = tinkerpad_plugin::manifest_schema();
    if let Some(object) = value.as_object_mut() {
        object.insert(
            "title".into(),
            serde_json::Value::String("TinkerPad plugin.toml".into()),
        );
        object.insert(
            "description".into(),
            serde_json::Value::String(
                "The manifest of a TinkerPad language plugin. Generated from the \
                 types the loader deserialises; see docs/PLUGINS.md §2."
                    .into(),
            ),
        );
    }
    let mut text = serde_json::to_string_pretty(&value).expect("a schema serialises");
    text.push('\n');
    text
}

fn manifest_page() -> String {
    let value = tinkerpad_plugin::manifest_schema();
    let defs = value
        .get("$defs")
        .and_then(|d| d.as_object())
        .cloned()
        .unwrap_or_default();

    let mut out = generated_by("the types in `crates/tinkerpad-plugin/src/manifest.rs`");
    out.push_str(
        "# Manifest reference\n\n\
         Every key `plugin.toml` accepts, from the types the loader actually uses.\n\
         The prose, and the reasoning, are in [PLUGINS.md](../PLUGINS.md) §2; this\n\
         is the list.\n\n\
         A machine-readable copy is [`plugin-toml.schema.json`](plugin-toml.schema.json).\n\
         Point your editor at it and the manifest is checked as you type.\n\n",
    );

    out.push_str(&table_for("The file", &value));
    let mut names: Vec<&String> = defs.keys().collect();
    names.sort();
    for name in names {
        let Some(def) = defs.get(name) else { continue };
        if def.get("properties").is_none() {
            continue;
        }
        out.push_str(&table_for(name, def));
    }
    out
}

/// One type as a table of its keys.
fn table_for(title: &str, schema: &serde_json::Value) -> String {
    let Some(properties) = schema.get("properties").and_then(|p| p.as_object()) else {
        return String::new();
    };
    let required: Vec<&str> = schema
        .get("required")
        .and_then(|r| r.as_array())
        .map(|list| list.iter().filter_map(|v| v.as_str()).collect())
        .unwrap_or_default();

    let mut out = format!("## {title}\n\n");
    if let Some(description) = schema.get("description").and_then(|d| d.as_str()) {
        out.push_str(&format!("{}\n\n", one_line(description)));
    }
    out.push_str("| Key | Type | Required | Meaning |\n|---|---|---|---|\n");

    let mut keys: Vec<&String> = properties.keys().collect();
    keys.sort();
    for key in keys {
        let property = &properties[key];
        let description = property
            .get("description")
            .and_then(|d| d.as_str())
            .map(one_line)
            .unwrap_or_default();
        out.push_str(&format!(
            "| `{key}` | {} | {} | {description} |\n",
            type_of(property),
            if required.contains(&key.as_str()) {
                "yes"
            } else {
                ""
            },
        ));
    }
    out.push('\n');
    out
}

/// A JSON Schema fragment as something a person reads in a table cell.
fn type_of(property: &serde_json::Value) -> String {
    if let Some(reference) = property.get("$ref").and_then(|r| r.as_str()) {
        let name = reference.rsplit('/').next().unwrap_or(reference);
        return format!("[{name}](#{})", anchor(name));
    }
    if let Some(list) = property.get("enum").and_then(|e| e.as_array()) {
        return list
            .iter()
            .filter_map(|v| v.as_str())
            .map(|v| format!("`{v}`"))
            .collect::<Vec<_>>()
            .join(" \\| ");
    }
    // `Option<T>` is `anyOf [T, null]`; an array is `items`.
    if let Some(list) = property.get("anyOf").and_then(|a| a.as_array()) {
        let parts: Vec<String> = list
            .iter()
            .filter(|v| v.get("type").and_then(|t| t.as_str()) != Some("null"))
            .map(type_of)
            .collect();
        return parts.join(" \\| ");
    }
    match property.get("type").and_then(|t| t.as_str()) {
        Some("array") => match property.get("items") {
            Some(items) => format!("array of {}", type_of(items)),
            None => "array".to_owned(),
        },
        Some("object") => "table".to_owned(),
        Some("boolean") => "boolean".to_owned(),
        Some("integer") | Some("number") => "number".to_owned(),
        Some("string") => "string".to_owned(),
        Some(other) => other.to_owned(),
        None => "any".to_owned(),
    }
}

fn anchor(name: &str) -> String {
    name.to_lowercase().replace(['_', ' '], "-")
}

fn one_line(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

// --- the two protocols ----------------------------------------------------

/// One example of every message, serialised by the real types.
fn helper_page() -> String {
    let main = PathBuf::from("/playgrounds/scratch-1/main.py");
    let dir = PathBuf::from("/playgrounds/scratch-1");
    let kind = tinkerpad_core::KindId::new("statements");

    let to = [
        ToHelper::Hello {
            protocol: tinkerpad_plugin::helper::PROTOCOL,
            plugin_dir: PathBuf::from("/plugins/python"),
            scratch_dir: PathBuf::from("/scratch/python"),
        },
        ToHelper::Run {
            id: "7".into(),
            main: main.clone(),
            dir: dir.clone(),
            kind: kind.clone(),
        },
        ToHelper::Cancel { id: "7".into() },
        ToHelper::Shutdown,
    ];
    let from = [
        FromHelper::Ready {
            name: Some("python helper".into()),
            version: Some("1.0".into()),
        },
        FromHelper::Stdout {
            id: "7".into(),
            data: "aGVsbG8K".into(),
        },
        FromHelper::Exited {
            id: "7".into(),
            code: Some(0),
            duration_ms: Some(12),
        },
        FromHelper::Failed {
            id: "7".into(),
            message: "the file did not compile".into(),
            diagnostics: Vec::new(),
        },
        FromHelper::Retiring {
            reason: Some("the module cache has grown too large".into()),
        },
    ];

    let mut out = generated_by("`crates/tinkerpad-plugin/src/helper/protocol.rs`");
    out.push_str(&format!(
        "# Helper protocol messages\n\n\
         `{}`, one JSON object per line over the helper's stdin and stdout.\n\
         What each message means, and the rules around them, are in\n\
         [PLUGINS.md](../PLUGINS.md) §5. These are the shapes, written by the\n\
         same code that sends them.\n\n\
         A field this build doesn't know is ignored in both directions, so a\n\
         newer core and an older helper keep working.\n\n## Core to helper\n\n",
        tinkerpad_plugin::helper::PROTOCOL
    ));
    for message in &to {
        out.push_str(&fenced(message));
    }
    out.push_str("## Helper to core\n\n");
    for message in &from {
        out.push_str(&fenced(message));
    }
    out.push_str(
        "## Hooks\n\n\
         A hook is a request with an `id`, answered by a `result` with the same\n\
         one. The request names the playground; the answer may ask for files to\n\
         be written inside it, and may carry settings for the language server.\n\n\
         A manifest lists the hooks its helper answers; one it doesn't list is\n\
         never sent.\n\n",
    );
    let playground = tinkerpad_core::Playground {
        id: tinkerpad_core::PlaygroundId::new("01J0TESTPLAYGROUND000001"),
        name: "Scratch 1".into(),
        language: tinkerpad_core::LanguageId::new("python"),
        kind: kind.clone(),
        dir: dir.clone(),
        main_file: main.clone(),
        created_ms: 0,
        tags: Vec::new(),
        pinned: false,
    };
    let hook = HookRequest::PlaygroundOpened {
        playground: playground.clone(),
        open: vec![playground],
    }
    .into_message("12".into());
    out.push_str(&fenced(&hook));
    out.push_str(&fenced(&FromHelper::Result {
        id: "12".into(),
        files: Vec::new(),
        lsp_config: None,
    }));
    out
}

fn dump_page() -> String {
    let column = |name: &str| Column {
        name: name.to_owned(),
        ty: None,
    };
    let values = [
        RichValue {
            v: tinkerpad_core::dump::VERSION,
            title: Some("answer".into()),
            id: None,
            node: RichNode::Value {
                value: serde_json::json!(42),
                ty: Some("int".into()),
            },
        },
        RichValue {
            v: tinkerpad_core::dump::VERSION,
            title: Some("people".into()),
            id: None,
            node: RichNode::Table {
                columns: vec![column("name"), column("n")],
                rows: vec![
                    vec![serde_json::json!("ada"), serde_json::json!(1)],
                    vec![serde_json::json!("grace"), serde_json::json!(2)],
                ],
                truncated: false,
            },
        },
        RichValue {
            v: tinkerpad_core::dump::VERSION,
            title: None,
            id: None,
            node: RichNode::Tree {
                value: serde_json::json!({ "a": [1, 2] }),
                ty: Some("dict".into()),
            },
        },
    ];

    let mut out = generated_by("`crates/tinkerpad-core/src/dump.rs`");
    out.push_str(
        "# Dump values\n\n\
         `tinkerpad-dump-v1`. A playground writes one of these inside an escape\n\
         sequence and TinkerPad takes it out of the output and renders it. The\n\
         sequence and the rules are in [PLUGINS.md](../PLUGINS.md) §6; these are\n\
         the payloads, written by the same types the output pane reads.\n\n",
    );
    for value in &values {
        out.push_str(&fenced(value));
    }
    out
}

/// A message as a fenced JSON block, from the type itself.
fn fenced<T: serde::Serialize>(value: &T) -> String {
    let json = serde_json::to_string_pretty(value).expect("these all serialise");
    format!("```json\n{json}\n```\n\n")
}
